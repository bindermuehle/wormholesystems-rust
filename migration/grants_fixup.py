#!/usr/bin/env python3
"""Replay the legacy map_access table onto an imported map.

Why this exists: a map export never contains its owner row, and the importer makes
whoever imports the file the owner. So after a stock import the previous owner has no
access at all -- on our maps the owner row was their *only* grant. Worse, when the
importing character already had a grant on that map it collides with the owner row the
import adds (map_access is unique on (map_id, subject_id)) and the real grant is gone
with no way to tell afterwards.

So the grants come from the source database rather than the file. For each map this
deletes every grant and writes the legacy set back verbatim, which makes the result
grant-for-grant identical to legacy instead of approximately right.

Reads the legacy MySQL over ssh, writes SQL to stdout. Nothing is applied: review it,
then pipe it to psql. Run with --check to only print the comparison.

    ./migration/grants_fixup.py > fixup.sql
    psql -d wormholesystems -f fixup.sql
"""

from __future__ import annotations

import argparse
import subprocess
import sys

# Laravel's polymorphic class names, and the role each legacy row becomes. A legacy
# owner row carries a permission of its own (ours are all `manager`), but the new model
# has one role per row and `owner` outranks every other, so the permission is dropped.
SUBJECT_TYPES = {
    "App\\Models\\Character": "character",
    "App\\Models\\Corporation": "corporation",
    "App\\Models\\Alliance": "alliance",
}
ROLES = {"viewer", "member", "manager"}

QUERY = """
select m.name, a.accessible_type, a.accessible_id, a.permission, a.is_owner,
       coalesce(date_format(a.expires_at, '%Y-%m-%dT%H:%i:%sZ'), '')
from maps m join map_access a on a.map_id = m.id
order by m.name, a.accessible_id
"""


def fetch(host: str, install_root: str) -> list[list[str]]:
    """The legacy grants, straight out of the container's mariadb client.

    The query travels over stdin rather than `-e`, so its own quotes do not have to
    survive ssh, `sh -c` and the shell inside the container.
    """
    remote = (
        f"cd {install_root} && docker compose exec -T mysql "
        f"sh -c 'exec mariadb -u$MYSQL_USER -p$MYSQL_PASSWORD $MYSQL_DATABASE -N -B'"
    )
    done = subprocess.run(
        ["ssh", "-o", "BatchMode=yes", host, remote],
        input=QUERY, capture_output=True, text=True,
    )
    if done.returncode != 0:
        sys.exit(f"reading the legacy database failed:\n{done.stderr.strip()}")
    out = done.stdout
    rows = [line.split("\t") for line in out.splitlines() if line.strip()]
    if not rows:
        sys.exit("no grants came back from the legacy database")
    return rows


def sql_str(value: str) -> str:
    """A Postgres string literal.

    Doubling the quote is the whole escape, and it is enough only while
    `standard_conforming_strings` is on, where a backslash is an ordinary character.
    That has been the default since 9.1 and the generated SQL sets it anyway rather
    than trusting the session it lands in.
    """
    if "\x00" in value:
        sys.exit(f"map name {value!r} contains a null byte")
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--host", default="ovhwormhole", help="ssh host of the legacy box")
    ap.add_argument("--install-root", default="/opt/wormholesystems-containers")
    ap.add_argument(
        "--check", action="store_true",
        help="print the grant counts per map and write no SQL",
    )
    args = ap.parse_args()

    rows = fetch(args.host, args.install_root)

    by_map: dict[str, list[tuple[str, int, str, str]]] = {}
    for name, acc_type, acc_id, permission, is_owner, expires in rows:
        subject = SUBJECT_TYPES.get(acc_type.replace("\\\\", "\\"))
        if subject is None:
            sys.exit(f"unknown accessible_type {acc_type!r} on map {name!r}")
        role = "owner" if is_owner == "1" else permission
        if role != "owner" and role not in ROLES:
            sys.exit(f"unknown permission {permission!r} on map {name!r}")
        by_map.setdefault(name, []).append((subject, int(acc_id), role, expires))

    for name, grants in sorted(by_map.items()):
        owners = [g for g in grants if g[2] == "owner"]
        if len(owners) != 1:
            sys.exit(f"map {name!r} has {len(owners)} owner rows, expected exactly 1")

    total = sum(len(g) for g in by_map.values())
    print(f"{len(by_map)} maps, {total} grants", file=sys.stderr)
    for name, grants in sorted(by_map.items()):
        owner = next(g for g in grants if g[2] == "owner")
        print(f"  {name:<14} {len(grants):>2} grants, owner character:{owner[1]}", file=sys.stderr)
    if args.check:
        return

    print("-- Generated by migration/grants_fixup.py. Replays the legacy grants onto")
    print("-- the imported maps, matched by name. Every grant on a named map is replaced.")
    print("begin;")
    print("set local standard_conforming_strings = on;")
    print()
    # A name that matches no map, or more than one, is a mistake worth stopping on
    # rather than silently skipping: it means the import did not land as expected.
    #
    # The names go into a temp table rather than into the pl/pgsql block below. A map
    # name is whatever a manager typed, and one containing `$$` would end the dollar
    # quoting and have the rest read as SQL. Inside a string literal it is just text.
    print("create temp table expected_maps (name text) on commit drop;")
    print("insert into expected_maps (name) values")
    print(",\n".join(f"    ({sql_str(name)})" for name in sorted(by_map)) + ";")
    print()
    print("""do $$
declare
    missing text;
begin
    for missing in select name from expected_maps loop
        if (select count(*) from maps where name = missing) <> 1 then
            raise exception 'expected exactly one map named %, found %',
                missing, (select count(*) from maps where name = missing);
        end if;
    end loop;
end $$;""")
    print()

    for name, grants in sorted(by_map.items()):
        # A `--` comment ends at the newline, so a map name carrying one would put the
        # rest of its own name on a line of its own, as SQL.
        print(f"-- {' '.join(name.split())}")
        print(f"delete from map_access where map_id = (select id from maps where name = {sql_str(name)});")
        values = []
        for subject, subject_id, role, expires in grants:
            expiry = sql_str(expires) + "::timestamptz" if expires else "null"
            values.append(
                f"    ((select id from maps where name = {sql_str(name)}), "
                f"'{subject}', {subject_id}, '{role}', {expiry})"
            )
        print("insert into map_access (map_id, subject_type, subject_id, role, expires_at) values")
        print(",\n".join(values) + ";")
        print()

    print("commit;")


if __name__ == "__main__":
    main()
